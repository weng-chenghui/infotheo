(******************************************************************************)
(** * DSDP Protocol in Chlipala-Style Coroutine-to-State-Machine Framework    *)
(**                                                                           *)
(** This file documents a potential future direction for expressing the DSDP   *)
(** protocol using the certified coroutine-to-state-machine derivation        *)
(** framework from:                                                           *)
(**                                                                           *)
(**   Ikebuchi, M., Erbsen, A., & Chlipala, A.                               *)
(**   "Certifying Derivation of State Machines from Coroutines"               *)
(**   POPL 2022. ACM, 2022.                                                   *)
(**   http://adam.chlipala.net/papers/CoroutinesPOPL22/                        *)
(**   Code: github.com/mit-plv/                                               *)
(**         certifying-derivation-of-state-machines-from-coroutines            *)
(**                                                                           *)
(** * Motivation                                                              *)
(**                                                                           *)
(** The current workflow to get an FSM from the protocol program is:          *)
(**                                                                           *)
(**   dsdp_pismc.v (monadic program `palice_n`)                               *)
(**       |                                                                   *)
(**       | manual construction (~2200 lines)                                 *)
(**       v                                                                   *)
(**   dsdp_fsm.v (Record `phase_state` + Inductive `phase_trans`              *)
(**               + 9 step-correctness lemmas)                                *)
(**       |                                                                   *)
(**       v                                                                   *)
(**   dsdp_fsm_progress.v (trace characterization from FSM)                   *)
(**                                                                           *)
(** The manual FSM construction is heavy labor (even with AI agents) because  *)
(** every state must be defined as a Record, every transition must be proved   *)
(** correct individually, and the whole thing must be kept in sync with the   *)
(** monadic program. For n parties, the loop unrolling creates O(n) states    *)
(** with repetitive but delicate proofs.                                      *)
(**                                                                           *)
(** The Chlipala framework eliminates this manual step entirely: a Coq tactic *)
(** ("derive") compiles the monadic program into an explicit state machine    *)
(** and simultaneously produces an equivalence proof. The output is:          *)
(**   - state : Set (auto-generated, one "variant" per yield point)           *)
(**   - step  : state -> eff -> rets -> state + ret_type (transition fn)      *)
(**   - equiv : the state machine faithfully simulates the coroutine          *)
(**                                                                           *)
(******************************************************************************)
(**                                                                           *)
(** * Framework Overview                                                      *)
(**                                                                           *)
(** ** Core type: free monad over effects                                     *)
(**                                                                           *)
(**   The program type is a free monad indexed by an effect signature:        *)
(**                                                                           *)
(**     Inductive t (ret_type : Set) :=                                       *)
(**     | Eff : forall (e : eff), args e -> (rets e -> t ret_type)            *)
(**                                         -> t ret_type                     *)
(**     | Return : ret_type -> t ret_type.                                    *)
(**                                                                           *)
(**   where:                                                                  *)
(**   - eff      : Set of effect names (e.g., send, recv)                     *)
(**   - args e   : argument type for effect e                                 *)
(**   - rets e   : return type for effect e                                   *)
(**   - Eff e a k: "perform effect e with argument a, bind result to k"       *)
(**   - Return v : "done, return v"                                           *)
(**                                                                           *)
(**   Monadic bind is a fixpoint:                                             *)
(**                                                                           *)
(**     Fixpoint bind (x : t T)(p : T -> t S) :=                             *)
(**       match x with                                                        *)
(**       | Return v => p v                                                   *)
(**       | Eff e a q => Eff e a (fun b => bind (q b) p)                     *)
(**       end.                                                                *)
(**     Notation "x <<- p ; e" := (bind p (fun x => e)).                     *)
(**                                                                           *)
(** ** Coroutines communicate via yield                                       *)
(**                                                                           *)
(**   A coroutine has type:                                                   *)
(**     t (const_yield A) (const_yield B) C                                   *)
(**   meaning it yields values of type A, receives values of type B,          *)
(**   and eventually returns a value of type C.                               *)
(**                                                                           *)
(**   Notation:                                                               *)
(**     v1 <- yield v2 ; e    (* yield v2 out, receive v1 back *)            *)
(**     n <- resume c $ x ; e (* parent resumes child c with input x *)      *)
(**                                                                           *)
(** ** State machine type (the compilation target)                            *)
(**                                                                           *)
(**   Definition step_type (ret_type state : Set) :=                          *)
(**     state -> forall (e : eff), rets e ->                                  *)
(**       (state * option { e : eff & args e }) + ret_type.                   *)
(**                                                                           *)
(**   Given current state and the return of the previous effect, produce:     *)
(**   - inl (next_state, Some (next_effect)) -- continue                      *)
(**   - inl (next_state, None)               -- halted/waiting                *)
(**   - inr return_value                     -- terminated                    *)
(**                                                                           *)
(** ** Compilation: three tactic entry points                                 *)
(**                                                                           *)
(**   derive' env   -- compile program with no coroutines (effects only)      *)
(**   derive_coro env -- compile a child coroutine (yield-based)              *)
(**   derive env    -- compile a parent that uses coroutines                  *)
(**                                                                           *)
(**   The env argument is a tuple of free variables: tt for none,             *)
(**   (tt, n) for one, (tt, fuel, certs, priv) for multiple.                 *)
(**                                                                           *)
(**   After Defined, extract via:                                             *)
(**     Definition my_step := projT1 (projT2 my_derive).                     *)
(**                                                                           *)
(** ** Recursion constraint                                                   *)
(**                                                                           *)
(**   The tactic only knows how to compile these specific loop forms:         *)
(**   - nat_rect_nondep (bounded iteration over nat)                          *)
(**   - list_rec_nondep (iteration over a list)                               *)
(**   Arbitrary Fixpoint/fix are NOT supported. This is a hard constraint.    *)
(**                                                                           *)
(** ** TLS 1.3 example (200+ line real protocol)                              *)
(**                                                                           *)
(**   The paper demonstrates the framework on a TLS 1.3 server handshake.    *)
(**   Effects are defined as flat inductive types (args_tls / rets_tls).      *)
(**   Each protocol operation (RecvClientHello, SendPacket, etc.) gets a      *)
(**   sugared notation wrapping the raw Eff + pattern matching:               *)
(**                                                                           *)
(**   Notation "r <- 'yield' 'RecvClientHello' ; p" :=                       *)
(**     (Eff yield (recvPacket RClientHello)                                  *)
(**          (fun r' => option_branch                                         *)
(**              (fun r => p)                                                 *)
(**              (fun al => Eff yield (closeWith al)                          *)
(**                             (fun _ => Return None))                       *)
(**              (fromRecvClientHello r'))).                                  *)
(**                                                                           *)
(**   The TLS handshake compiles via:                                         *)
(**                                                                           *)
(**   Lemma doHandshake_derive :                                              *)
(**     { state & { step &                                                    *)
(**       forall fuel certs priv,                                             *)
(**         { init | @equiv_coro _ _ _ _ _ state step init                    *)
(**                              (doHandshake fuel certs priv) } } }.         *)
(**   Proof.                                                                  *)
(**     do 3 eexists. unfold doHandshake. intros.                             *)
(**     Time unshelve derive_coro (tt,fuel,certs,priv);                       *)
(**       intros; exact inhabitant.                                           *)
(**   Time Defined.                                                           *)
(**                                                                           *)
