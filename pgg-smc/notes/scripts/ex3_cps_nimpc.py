print_separator("Summary")
print("""
CPS (Commuting Permutation System):
  ALL generator pairs commute  =>  evaluation order is completely free.
  Every permutation of the party order yields the same product.
  Example: cyclic group Z/4Z ≤ S_4 — all elements are powers of one cycle.

Non-commuting system (S_3 fragment):
  σ = (0 1 2) and τ = (0 1) do NOT commute.
  When parties select these generators, the evaluation order matters.
  This violates the CPS condition — NIMPC is not supported directly.

RAAG middle ground:
  Some pairs commute (edges in Γ), others do not (non-edges).
  Reorderings that only swap commuting adjacent generators are free.
  Reorderings that cross a non-commuting pair change the product.
  The safe reorderings are exactly the trace-equivalence classes of the
  trace monoid M(Σ, I) where I is the commutativity (independence) relation.
""")
