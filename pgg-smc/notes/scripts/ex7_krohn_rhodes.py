"""
Example 7: Cascade Decomposition via Krohn-Rhodes Theorem (§7.3)
=================================================================
Demonstrates how a non-group automaton (one with non-invertible transitions)
is decomposed into a cascade of:
  - a GROUP layer  (cyclic group Z/4Z — handled by SMC-PGG monodromy walk)
  - an APERIODIC layer  (reset/collapse map — handled by a threshold protocol)

Setup: 4-state automaton with 2 generators
  States:  {0, 1, 2, 3}
  σ (group):     cyclic permutation (0 1 2 3)  — invertible, order 4
  ρ (aperiodic): collapsing map 0→0, 1→0, 2→2, 3→2  — NOT invertible

Krohn-Rhodes theorem (informal):
  Every finite automaton / transformation monoid M decomposes as a
  "wreath product cascade" of simpler pieces, each of which is either
  a simple group or a 2-element aperiodic (reset) monoid.

  Here the transformation monoid ⟨σ, ρ⟩ has:
    - A group submonoid isomorphic to Z/4Z (generated by σ)
    - An aperiodic quotient capturing ρ

SMC-PGG handling:
  - Group layer:     parties run the standard monodromy walk on Z/4Z
  - Aperiodic layer: parties run a 1-bit broadcast ("did ρ fire?")
  - Cascade:         group-layer output feeds aperiodic layer via the
                     wreath-product coordinate update rule
"""

