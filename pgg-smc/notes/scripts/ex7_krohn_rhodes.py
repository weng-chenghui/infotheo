    while queue_g:
        cur = queue_g.pop(0)
        for g in perm_gens:
            # compose: cur then g
            nxt_perm = [g.perm[cur.perm[i]] for i in range(n5)]
            nxt = Permutation(nxt_perm)
            key = tuple(nxt.perm)
            if key not in group_set:
                group_set[key] = nxt
                queue_g.append(nxt)

    group_order = len(group_set)
    print(f"    |⟨α, β⟩| = {group_order}")
    if group_order >= 60:
        print("    ✓ |⟨α, β⟩| ≥ 60  →  contains A_5  →  NON-SOLVABLE group.")
    else:
        print(f"    ✗ |⟨α, β⟩| = {group_order} < 60  (unexpected — check generators).")
    print()

    # ------------------------------------------------------------------
    # 3. Demonstrate AND(x1, x2) via commutator [α^x1, β^x2]
    # ------------------------------------------------------------------
    print("  ─── 3. AND(x1, x2) via group-layer commutator [α^x1, β^x2] ───")
    print()
    print("    Barrington (1989): NC^1 circuits ↔ width-5 branching programs")
    print("    over a non-solvable group.  AND is computed by [α^x1, β^x2]:")
    print("      x1=0 or x2=0  ↦  commutator = id")
    print("      x1=1 and x2=1 ↦  commutator ≠ id  (non-trivial element of A_5)")
    print()
    print(f"    {'x1':<5} {'x2':<5} {'[α^x1, β^x2]':<30} {'= id?':<8} {'AND'}")
    print(f"    {'-'*5} {'-'*5} {'-'*30} {'-'*8} {'-'*5}")

    comm_11 = None
    for x1 in [0, 1]:
        for x2 in [0, 1]:
            # α^x1: x1=0 → id, x1=1 → α
            a = alpha_p if x1 == 1 else identity_p
            b = beta_p  if x2 == 1 else identity_p
            comm = commutator(a, b)   # a^-1 b^-1 a b  (or a b a^-1 b^-1)
            is_id = (comm.perm == list(range(n5)))
            and_val = x1 & x2
            expected_id = (and_val == 0)
            mark = "OK" if (is_id == expected_id) else "FAIL"
            print(f"    {x1:<5} {x2:<5} {str(comm.perm):<30} {'yes' if is_id else 'no':<8} {and_val}  {mark}")
            if x1 == 1 and x2 == 1:
                comm_11 = comm
    print()
    print(f"    [α, β] = {comm_11.perm}  (non-identity element of A_5 used as AND witness)")
    print()
    print("    A solvable group (like Z/4Z) has no pair of elements whose")
    print("    commutator witnesses AND in this way — its derived series reaches")
    print("    {id} in finitely many steps, so commutators eventually trivialize.")
    print()

    # ------------------------------------------------------------------
    # 4. Cascade: evaluate mixed words [alpha, beta, rho5, alpha] on all
    #    5 starting states
    # ------------------------------------------------------------------
    print("  ─── 4. Cascade evaluation of [α, β, ρ, α] on 5-state automaton ───")
    print()

    demo_words_5 = [
        ["alpha", "beta", "rho5", "alpha"],
        ["alpha", "beta", "alpha", "rho5"],
        ["rho5", "alpha", "beta"],
        ["alpha", "alpha", "alpha", "alpha", "alpha"],  # α^5 = id
    ]

    states5 = list(range(5))
    print(f"    {'Word':<40} {'Start':<6} {'Result'}")
    print(f"    {'-'*40} {'-'*6} {'-'*6}")
