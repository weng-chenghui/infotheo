def cascade_evaluate(word: List[str], start: int) -> int:
    """
    Evaluate word on start state using the Krohn-Rhodes cascade:
      - offset tracks position within the Z/4Z orbit (mod 4)
      - 'orbit' bit is not changed by either generator in this automaton
        because σ is a single 4-cycle covering all states, and ρ is
        defined by snapping offset to 0.

    Concretely:
      State s has offset = s (all 4 states are in a single orbit under σ).
      σ: s -> (s+1) mod 4
      ρ: s -> (s // 2) * 2   (snap to even = pair-root)
    """
    s = start
    for letter in word:
        if letter == "sigma":
            s = (s + 1) % 4
        elif letter == "rho":
            s = (s // 2) * 2
        else:
            raise ValueError(f"Unknown letter: {letter!r}")
    return s


