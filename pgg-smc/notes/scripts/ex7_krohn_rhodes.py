# Transformation: a function {0,1,2,3} -> {0,1,2,3}
# Represented as a list t where t[i] = image of state i.

class Transformation:
    """A (not necessarily invertible) function on {0,...,n-1}."""

    def __init__(self, table: List[int]):
        self.table = list(table)
        self.n = len(table)

    def __call__(self, state: int) -> int:
        return self.table[state]

    def compose(self, other: 'Transformation') -> 'Transformation':
        """self after other: (self ∘ other)(x) = self(other(x))."""
        return Transformation([self.table[other.table[i]] for i in range(self.n)])

    def __mul__(self, other: 'Transformation') -> 'Transformation':
        """Left-to-right: self * other means apply self first, then other."""
        return other.compose(self)

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, Transformation):
            return NotImplemented
        return self.table == other.table

    def __hash__(self) -> int:
        return hash(tuple(self.table))

    def __repr__(self) -> str:
        return f"[{', '.join(str(x) for x in self.table)}]"

    def is_permutation(self) -> bool:
        return sorted(self.table) == list(range(self.n))

    def image(self):
        return sorted(set(self.table))

    def is_idempotent(self) -> bool:
        """f is idempotent if f ∘ f = f (characteristic of aperiodic elements)."""
        return self.compose(self) == self

    def is_aperiodic(self) -> bool:
        """An element m is aperiodic if some power m^k = m^(k+1), i.e.,
        all cycles in the functional graph have length 1 (fixed points only)."""
        # Iterate to find a fixed power
        cur = Transformation(list(self.table))
        seen = {}
        for k in range(1, self.n + 2):
            key = tuple(cur.table)
            if key in seen:
                # We cycled — if the cycle length is 1, aperiodic
                prev_k = seen[key]
                return (k - prev_k) == 1
            seen[key] = k
            cur = cur.compose(self)
        return True

    def fmt(self) -> str:
        return " ".join(f"{i}→{self.table[i]}" for i in range(self.n))


def transformation_monoid(generators: Dict[str, Transformation]) -> Dict[tuple, Transformation]:
    """Enumerate all elements of the transformation monoid by closure."""
    n = next(iter(generators.values())).n
    identity = Transformation(list(range(n)))
    monoid: Dict[tuple, Transformation] = {}
    queue = [identity]
    monoid[tuple(identity.table)] = identity

    while queue:
        cur = queue.pop(0)
        for gen in generators.values():
            # left-to-right product: cur * gen
            nxt = cur * gen
            key = tuple(nxt.table)
            if key not in monoid:
                monoid[key] = nxt
                queue.append(nxt)

    return monoid


def evaluate_word_trans(word: List[str],
                        generators: Dict[str, Transformation]) -> Transformation:
    """Evaluate a word as a left-to-right product of transformations."""
    n = next(iter(generators.values())).n
    result = Transformation(list(range(n)))
    for letter in word:
        result = result * generators[letter]
    return result


