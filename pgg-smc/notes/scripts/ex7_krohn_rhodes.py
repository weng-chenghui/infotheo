    print("    ├────────────────────┼──────────────────────────────────────────┤")
    print("    │ Z/4Z (Sects. 1-8)  │ Abelian → commutators trivial → cannot   │")
    print("    │                    │ witness AND via [g^x1, h^x2] trick.       │")
    print("    │                    │ Equivalent to additive secret sharing.    │")
    print("    ├────────────────────┼──────────────────────────────────────────┤")
    print("    │ A_5 / S_5 (Sect.9) │ Non-solvable → [α^x1, β^x2] gives AND.  │")
    print("    │                    │ Barrington: width-5 branching programs   │")
    print("    │                    │ over A_5 compute ALL of NC^1.            │")
    print("    │                    │ Cannot be replaced by any solvable group. │")
    print("    └────────────────────┴──────────────────────────────────────────┘")
    print()
