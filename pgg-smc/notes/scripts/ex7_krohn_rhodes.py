def make_generators() -> Dict[str, Transformation]:
    # σ: cyclic (0 1 2 3)
    sigma = Transformation([1, 2, 3, 0])
    # ρ: collapse pairs — 0→0, 1→0, 2→2, 3→2
    rho   = Transformation([0, 0, 2, 2])
    return {"sigma": sigma, "rho": rho}


# Also expose σ as a Permutation for the SMC-PGG monodromy walk
def make_z4_monodromy() -> MonodromyGroup:
    """Z/4Z acting on {0,1,2,3}: generator σ = (0 1 2 3)."""
    n = 4
    sigma_perm = Permutation.from_cycles(n, (0, 1, 2, 3))
    # Include sigma and its inverse for completeness
    generators = {
        "sigma":    sigma_perm,
        "-sigma":   sigma_perm.inverse(),   # sigma^3 = (0 3 2 1)
    }
    return MonodromyGroup(n_sheets=n, generators=generators)


