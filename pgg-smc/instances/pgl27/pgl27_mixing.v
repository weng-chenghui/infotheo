(** Wuni — the uniform letter distribution of the realistic word shuffle.
    @intent: the letter law of the L-word shuffle. *)
Definition Wuni : R.-fdist 'I_5 := fdist_uniform (card_ord 5).

Local Lemma absN_toR (a b : N) :
  (N.to_nat (absdiffN a b))%:R = `|(N.to_nat a)%:R - (N.to_nat b)%:R| :> R.
Proof.
rewrite /absdiffN; case: ifPn => H.
- move/N.ltb_lt/N.lt_le_incl: H => Hle.
  have Hadd := congr1 N.to_nat (N.sub_add _ _ Hle).
  rewrite N2Nat.inj_add plusE in Hadd.
  have Hsub : (N.to_nat (b - a) = N.to_nat b - N.to_nat a)%N by rewrite -Hadd addnK.
  have Hle2 : (N.to_nat a <= N.to_nat b)%N by rewrite -Hadd leq_addl.
  by rewrite Hsub natrB // ler0_norm ?subr_le0 ?ler_nat // opprB.
- move/negbTE: H => /N.ltb_ge Hle.
  have Hadd := congr1 N.to_nat (N.sub_add _ _ Hle).
  rewrite N2Nat.inj_add plusE in Hadd.
  have Hsub : (N.to_nat (a - b) = N.to_nat a - N.to_nat b)%N by rewrite -Hadd addnK.
  have Hle2 : (N.to_nat b <= N.to_nat a)%N by rewrite -Hadd leq_addl.
  by rewrite Hsub natrB // ger0_norm ?subr_ge0 ?ler_nat.
Qed.

Local Lemma frac_diff (c D : nat) : (0 < D)%N ->
  c%:R / D%:R - 336%:R^-1 = ((336 * c)%:R - D%:R) / (336 * D)%:R :> R.
Proof.
move=> DP.
have HD : (D%:R : R) != 0 by rewrite pnatr_eq0 -lt0n.
have H336 : (336%:R : R) != 0 by rewrite pnatr_eq0.
have HDD : ((336 * D)%:R : R) != 0 by rewrite pnatr_eq0 muln_eq0 negb_or -!lt0n DP.
apply: (mulIf HDD).
rewrite divfK // natrM mulrBl natrM; congr (_ - _).
  by rewrite mulrCA divfK // mulrC.
by rewrite mulrA mulVf // mul1r.
Qed.

Local Lemma final_bound_gen (SN D : nat) :
  (0 < D)%N -> (2 ^ 40 * SN <= 336 * D)%N ->
  SN%:R / (336 * D)%:R <= 2%:R^-40 :> R.
Proof.
move=> DP Hc.
have HDD : (0 < (336 * D)%:R :> R) by rewrite ltr0n muln_gt0 DP.
rewrite ler_pdivrMr //.
have -> : 2%:R^-40 * (336 * D)%:R = (336 * D)%:R / (2 ^ 40)%:R :> R.
  by rewrite natrX -exprVn mulrC.
rewrite ler_pdivlMr ?ltr0n ?expn_gt0 //.
by rewrite -natrM ler_nat mulnC.
Qed.

Local Lemma rho_valE (g : {perm 'I_8}) :
  @rho_from_words_weighted R 6 4 200 pgl27_sym_sigmas Wuni g
  = (fibc 200 g)%:R / (5 ^ 200)%:R.
Proof.
rewrite fiber_prob_weighted.
rewrite (eq_bigr (fun=> (5 ^ 200)%:R^-1)); last first.
  move=> w _.
  rewrite word_weightedE.
  under eq_bigr => i _ do rewrite /Wuni fdist_uniformE card_ord.
  by rewrite prodr_const card_ord exprVn natrX.
by rewrite sumr_const [X in _ = X]mulrC mulr_natr; congr (_ *+ _).
Qed.

Local Lemma mixing_bound_gen
  (Gg : {group {perm 'I_8}}) (ep : nat -> {perm 'I_8}) (vN : nat -> N)
  (GposH : (0 < #|Gg|)%N) :
  #|Gg| = 336 ->
  (forall g, g \in Gg -> g \in [seq ep k | k <- iota 0 336]) ->
  {in iota 0 336 &, injective ep} ->
  (forall k, ep k \in Gg) ->
  (forall k, (k < 336)%N -> fibc 200 (ep k) = N.to_nat (vN k)) ->
  (forall w : 200.-tuple 'I_5, weval w \in Gg) ->
  (2 ^ 40 * (\sum_(k < 336) N.to_nat (absdiffN (336 * vN k) (5 ^ 200)%num))
   <= 336 * 5 ^ 200)%N ->
  var_dist (@rho_from_words_weighted R 6 4 200 pgl27_sym_sigmas Wuni) (`U GposH)
  <= 2%:R^-40.
Proof.
move=> Hcard mem_Gg ep_inj ep_mem fibcnt word_in_G Hcert.
rewrite /var_dist (bigID (fun g => g \in Gg)) /=.
rewrite [X in _ + X]big1 ?addr0; last first.
  move=> g Hg.
  have Hf0 : fibc 200 g = 0.
    rewrite /fibc; apply/eqP; rewrite cards_eq0; apply/eqP; apply/setP => w.
    rewrite !inE; apply/negbTE; apply: contra Hg => /eqP <-; exact: word_in_G.
  by rewrite rho_valE Hf0 mul0r fdist_uniform_supp_notin // subr0 normr0.
have Hperm : perm_eq (enum Gg) [seq ep k | k <- iota 0 336].
  apply: uniq_perm; first exact: enum_uniq.
    by rewrite (map_inj_in_uniq ep_inj); exact: iota_uniq.
  move=> g; rewrite mem_enum.
  apply/idP/idP; first exact: mem_Gg.
  by move=> /mapP[k _ ->]; exact: ep_mem.
rewrite -big_enum (perm_big _ Hperm) big_map.
rewrite -[iota 0 336]/(index_iota 0 336) big_mkord.
rewrite (eq_bigr (fun i : 'I_336 =>
  (N.to_nat (absdiffN (336 * vN i) (5 ^ 200)%num))%:R / (336 * 5 ^ 200)%:R));
    last first.
  move=> i _.
  rewrite rho_valE (fibcnt _ (ltn_ord i)) fdist_uniform_supp_in ?ep_mem // Hcard.
  rewrite frac_diff ?expn_gt0 // normrM normfV.
  rewrite (absN_toR (336 * vN i)%num (5 ^ 200)%num) N2Nat.inj_mul multE NtoNat_pow.
  by rewrite [`|(336 * 5 ^ 200)%:R|]ger0_norm ?ler0n.
rewrite -mulr_suml -natr_sum.
by apply: final_bound_gen; [rewrite expn_gt0 | exact: Hcert].
Qed.

(** pgl27_word_mixing — the law of a uniform 200-letter generator word is
    within 2^-40 of the uniform shuffle in variation distance.
    @main security: the realistic-shuffle mixing certificate. *)
Lemma pgl27_word_mixing :
  var_dist (@rho_from_words_weighted R 6 4 200 pgl27_sym_sigmas Wuni)
           (`U pgl27_G_pos)
  <= 2%:R^-40.
Proof.
apply: (@mixing_bound_gen (pgg_G pgl27_M)%G entry_perm
  (fun k => nth 0%num (walkN 200) k) pgl27_G_pos pgl27_card mem_G_Ps
  entry_perm_inj entry_perm_mem (fun k : nat => @fiber_count 200 k)
  (@word_eval_in_G 200) mixing_cert_nat).
Qed.

