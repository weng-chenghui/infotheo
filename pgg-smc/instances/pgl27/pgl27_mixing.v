move=> Hk.
have Hkp : (k < size pred_table)%N by rewrite size_pred_table.
rewrite walkS (nth_map [::] _ _ Hkp) (nth_pred_table Hk) foldlN_addsum.
rewrite [N.to_nat 0%num]/= add0n big_map.
rewrite -[ [:: 0; 1; 2; 3; 4] ]/(index_iota 0 5) big_mkord.
exact: erefl.
Qed.

(* The fibre of length L over the identity is the walk's L-step count. *)
Local Lemma fiber_count (L k : nat) : (k < 336)%N ->
  fibc L (entry_perm k) = N.to_nat (nth 0%num (walkN L) k).
Proof.
elim: L k => [|L IH] k Hk.
- rewrite fibc0.
  have Hek : (entry_perm k == 1%g) = (k == 0).
    apply/idP/idP.
    - move/eqP => H1k.
      have H0 : (0 < size elem_table)%N by rewrite size_elem_table.
      have Hp : nth [::] (unzip1 elem_table) k = nth [::] (unzip1 elem_table) 0.
        rewrite -(ptbl_entry Hk) H1k ptbl_id.
        by rewrite /unzip1 (nth_map ([::], [::]) _ _ H0) elem_table0.
      have Hks : (k < size (unzip1 elem_table))%N by rewrite keys_size.
      have H0s : (0 < size (unzip1 elem_table))%N by rewrite keys_size.
      move: Hp => /eqP.
      rewrite (nth_uniq _ Hks H0s uniq_elem_keys).
      by move/eqP => ->.
    - by move/eqP => ->; rewrite /entry_perm elem_table0 /word5_perm.
  rewrite Hek.
  case: k {Hek} Hk => [|k'] Hk; first by [].
  rewrite -[walkN 0]/(1%num :: nseq 335 0%num).
  rewrite -[nth 0%num (1%num :: nseq 335 0%num) k'.+1]
           /(nth 0%num (nseq 335 0%num) k').
  by rewrite nth_nseq if_same.
- rewrite fibc_rec (@walk_step L k Hk).
  apply: eq_bigr => j _.
  rewrite (@entry_pred k j Hk) (IH _ (predk_lt Hk (ltn_ord j))).
  exact: erefl.
Qed.

