(*  Section 4. The mixing coefficient alpha and the imported Rayleigh bound.   *)
(******************************************************************************)

(* alpha is a rational upper bound on the second-largest eigenvalue modulus of
   the symmetric Schreier walk on the 14 cards, supplied by
   wreath_spectral_certificate.py in this directory. Analytically the second
   eigenvalue is 3/5 + (2/5) cos(2 pi / 7) ~ 0.84940, and 17/20 = 0.85 bounds it
   (cos(2 pi / 7) < 5/8). It is a rational in [0, 1); the [0,1) bounds below are
   proved, and the certificate attests that alpha^2 * I - Q^2 is PSD on the
   mean-zero hyperplane (all 13 LDL^T pivots strictly positive), i.e. the
   Rayleigh bound wreath_rayleigh_Qsq_R. The wreath gap 1 - alpha = 3/20 is
   wider than the S_5 gap 19/200: the wreath mixes faster. *)
Definition wreath_alpha_R (R : realType) : R := 17%:R / 20%:R.

(** wreath_alpha_R_ge0 — the wreath mixing coefficient is non-negative.
    Kind: helper. Why: locates alpha in [0,1]. Used by: wreath_gap_R_le1. *)
Lemma wreath_alpha_R_ge0 (R : realType) : 0 <= wreath_alpha_R R.
Proof. rewrite /wreath_alpha_R; apply divr_ge0; by rewrite ler0n. Qed.

(** wreath_alpha_R_le1 — the wreath mixing coefficient is at most one.
    Kind: helper. Why: with ge0, locates alpha in [0,1].
    Used by: wreath_gap_R_le1. *)
Lemma wreath_alpha_R_le1 (R : realType) : wreath_alpha_R R <= 1.
Proof.
rewrite /wreath_alpha_R ler_pdivrMr ?mul1r; last by rewrite ltr0n.
by rewrite ler_nat.
Qed.

(** wreath_alpha_R_lt1 — the wreath mixing coefficient is strictly below one.
    Kind: helper. Why: strict bound makes the spectral gap positive.
    Used by: wreath_gap_R_pos. *)
Lemma wreath_alpha_R_lt1 (R : realType) : wreath_alpha_R R < 1.
Proof.
rewrite /wreath_alpha_R ltr_pdivrMr ?mul1r; last by rewrite ltr0n.
by rewrite ltr_nat.
Qed.

(** AXIOM STATUS: certified externally by wreath_spectral_certificate.py in
    this directory (the Z_7 wr S_2 analogue of s5_spectral_certificate.py).
    Only the Rayleigh conclusion enters this development, exactly as for
    s5_rayleigh_Qsq_R. *)
Axiom wreath_rayleigh_Qsq_R :
  forall (R : realType) (v : 'cV[R]_14),
  \sum_i v i ord0 = 0 ->
  (v^T
    *m (schreier_transition R wreath_sym_gens
        *m schreier_transition R wreath_sym_gens)
    *m v) ord0 ord0
  <= (wreath_alpha_R R) ^+ 2 * cV_inner v v.

