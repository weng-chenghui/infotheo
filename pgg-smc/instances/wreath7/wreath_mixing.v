(** wreath_schreier_col_sum — column sums of the symmetric Schreier transition
    equal 1.
    Kind: helper.
    Why: the row sums are 1 generically (stochastic); the column sums follow
    from symmetry (wreath_schreier_symm), giving double stochasticity, which is
    the hypothesis symm_ds_TV_bound_cV needs. Mirrors
    schreier_transition_doubly_stochastic_col, but draws symmetry from
    multiset inverse-closure rather than per-generator involutivity.
    Used by: wreath_spectral_convergence_proved. *)
Lemma wreath_schreier_col_sum (R : realType) (j : 'I_14) :
  \sum_i schreier_transition R wreath_sym_gens i j = 1.
Proof.
have Hsym := wreath_schreier_symm R.
transitivity (\sum_i schreier_transition R wreath_sym_gens j i).
  apply: eq_bigr => i _.
  have /matrixP /(_ j i) := Hsym.
  by rewrite mxE.
exact: schreier_transition_stochastic.
Qed.

(** wreath_schreier_endpoint_eq — the wreath endpoint pushforward equals the
    matrix-power column entry.
    Kind: helper.
    Why: the bridge from the probabilistic endpoint law fdistmap(sigma s) to
    (Q^L *m e_s), required to feed the column-vector TV engine. Mirrors
    schreier_endpoint_eq_Q_power, using wreath_schreier_symm for the Q^L
    transpose-symmetry and the generic schreier_walk_eq_endpoint.
    Used by: wreath_spectral_convergence_proved. *)
Lemma wreath_schreier_endpoint_eq (R : realType) (L : nat) (s a : 'I_14) :
  fdistmap (fun sigma : {perm 'I_14} => sigma s)
           (rho_from_words L wreath_sym_gens) a
  = ((schreier_transition R wreath_sym_gens) ^+ L
       *m \col_i (i == s)%:R) a ord0.
Proof.
have Hsym := wreath_schreier_symm R.
have HQLsymm :
  ((schreier_transition R wreath_sym_gens) ^+ L)^T
    = (schreier_transition R wreath_sym_gens) ^+ L.
  elim: L => [|L' IH].
    by rewrite expr0 trmx1.
  by rewrite exprS trmx_mul IH -exprS exprSr Hsym.
have entry_eq : forall i j,
    ((schreier_transition R wreath_sym_gens) ^+ L) i j
      = ((schreier_transition R wreath_sym_gens) ^+ L) j i.
  move=> i j.
  have /matrixP /(_ j i) := HQLsymm.
  by rewrite mxE.
rewrite mxE.
rewrite (bigD1 s)//= mxE eqxx mulr1 big1; last first.
  by move=> j /negPf Hj; rewrite mxE Hj mulr0.
rewrite addr0 entry_eq.
by rewrite -schreier_walk_eq_endpoint.
Qed.

(** wreath_spectral_convergence_proved — the wreath endpoint law is within
    sqrt(14) * alpha^L of uniform.
    Kind: main.
    Why: feeds wreath_spectral_convergence_gap and the SchreierCertificate.
    Proof assembles symm_ds_TV_bound_cV (Q symmetric via wreath_schreier_symm,
    doubly stochastic, Rayleigh via wreath_rayleigh_Qsq_R) with the endpoint
    bridge, exactly as symm_ds_TV_bound does for the involutive case. *)
Lemma wreath_spectral_convergence_proved
    (R : realType) (L : nat) (s : 'I_14) :
  var_dist (fdistmap (fun sigma : {perm 'I_14} => sigma s)
                     (rho_from_words L wreath_sym_gens))
           (fdist_uniform (card_ord 14))
  <= Num.sqrt 14%:R * (wreath_alpha_R R) ^+ L.
Proof.
set Q := schreier_transition R wreath_sym_gens.
have Q_row_sum : forall i : 'I_14, \sum_j Q i j = 1
  by exact: schreier_transition_stochastic.
have Q_col_sum : forall j : 'I_14, \sum_i Q i j = 1
  by exact: wreath_schreier_col_sum.
have Q_symm : Q^T = Q by exact: wreath_schreier_symm.
rewrite /var_dist.
have HtoCol :
  \sum_a `|fdistmap (fun sigma : {perm 'I_14} => sigma s)
            (rho_from_words L wreath_sym_gens) a
        - fdist_uniform (card_ord 14) a|
  = \sum_a `|(Q ^+ L *m \col_i (i == s)%:R) a ord0
            - (\col_i (#|'I_14|%:R^-1 : R)) a ord0|.
  apply: eq_bigr => a _.
  congr `|_|; congr (_ - _).
    rewrite /Q.
    exact: (wreath_schreier_endpoint_eq R L s a).
  by rewrite mxE fdist_uniformE.
rewrite HtoCol.
have HsqrtN_eq : Num.sqrt (14%:R : R) = Num.sqrt (#|'I_14|%:R)
  by rewrite card_ord.
rewrite HsqrtN_eq.
exact: (@symm_ds_TV_bound_cV R 13 Q Q_row_sum Q_col_sum Q_symm
          (wreath_alpha_R R) (wreath_alpha_R_ge0 R)
          (@wreath_rayleigh_Qsq_R R) L s).
Qed.

