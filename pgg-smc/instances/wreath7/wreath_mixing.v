(** wreath_sym_gens — the inverse-closed five-generator multiset of Z_7 wr S_2.
    Kind: instance.
    Why: cut1, cut2 are 7-cycles, so the bare [cut1; cut2; wswap] Schreier
    transition is not symmetric. Adjoining cut1^-1, cut2^-1 (wswap is its own
    inverse) closes the multiset under inverse, making the transition symmetric
    without changing the generated group.
    Used by: M_wreath_sym, wreath_schreier_symm, wreath_rayleigh_Qsq_R. *)
Definition wreath_sym_gens : 5.-tuple {perm 'I_14} :=
  [tuple cut1; (cut1^-1)%g; cut2; (cut2^-1)%g; wswap].

(** M_wreath_sym — the wreath monodromy over the inverse-closed generators.
    Kind: instance.
    Why: same group as M_wreath (Z_7 wr S_2 on 14 cards), but with the
    symmetric generating multiset, so its Schreier walk admits the spectral
    mixing argument. Carries the SecurityAsymptotic below. *)
Definition M_wreath_sym : MonodromyReprWithGeneratorType :=
  @Gen_PGGTypes 4 12 wreath_sym_gens.

(** wreath_sym_same_group — adjoining inverses preserves the generated group.
    Kind: helper.
    Why: certifies that the symmetric monodromy M_wreath_sym is still the
    wreath Z_7 wr S_2, so the plug's structural anonymity (|G| = 98,
    non-abelian) is unchanged by the symmetrisation.
    Used by: the plug rewiring; not load-bearing for the mixing bound. *)
Lemma wreath_sym_same_group : pgg_G M_wreath_sym = pgg_G M_wreath.
Proof.
rewrite /M_wreath_sym /M_wreath /=.
apply/val_inj => /=; apply/eqP; rewrite eqEsubset; apply/andP; split.
- (* <<S5>> <= <<S3>>: every symmetric generator lies in <<S3>>; the inverses
     cut1^-1, cut2^-1 via groupV. *)
  rewrite gen_subG; apply/subsetP => x /imsetP [i _ ->].
  have memg : forall j : 'I_3,
      tnth wreath_gens j \in <<[set tnth wreath_gens i0 | i0 : 'I_3]>>%G.
    by move=> j; apply: mem_gen; apply/imsetP; exists j.
  case: i => -[|[|[|[|[|i']]]]] Hi //; rewrite (tnth_nth 1%g) /=.
  + by have := memg (@Ordinal 3 0 isT); rewrite (tnth_nth 1%g) /=.
  + rewrite groupV.
    by have := memg (@Ordinal 3 0 isT); rewrite (tnth_nth 1%g) /=.
  + by have := memg (@Ordinal 3 1 isT); rewrite (tnth_nth 1%g) /=.
  + rewrite groupV.
    by have := memg (@Ordinal 3 1 isT); rewrite (tnth_nth 1%g) /=.
  + by have := memg (@Ordinal 3 2 isT); rewrite (tnth_nth 1%g) /=.
- (* <<S3>> <= <<S5>>: S3 is a subset of S5, then genS. *)
  apply: genS; apply/subsetP => y /imsetP [j _ ->].
  case: j => -[|[|[|j']]] Hj //; rewrite (tnth_nth 1%g) /=.
  + by apply/imsetP; exists (@Ordinal 5 0 isT); rewrite ?(tnth_nth 1%g) /=.
  + by apply/imsetP; exists (@Ordinal 5 2 isT); rewrite ?(tnth_nth 1%g) /=.
  + by apply/imsetP; exists (@Ordinal 5 4 isT); rewrite ?(tnth_nth 1%g) /=.
Qed.

