(** wreath_gap_R — the wreath spectral gap, 1 - alpha.
    Kind: definition. Why: the gap form consumed by the SchreierCertificate. *)
Definition wreath_gap_R (R : realType) : R := 1 - wreath_alpha_R R.

(** wreath_gap_R_pos — the wreath spectral gap is strictly positive.
    Kind: helper. Why: positivity drives geometric convergence.
    Used by: wreath_schreier_certificate. *)
Lemma wreath_gap_R_pos (R : realType) : 0 < wreath_gap_R R.
Proof. rewrite /wreath_gap_R subr_gt0; exact: wreath_alpha_R_lt1. Qed.

(** wreath_gap_R_le1 — the wreath spectral gap is at most one.
    Kind: helper. Why: with pos, places gap in [0,1].
    Used by: wreath_schreier_certificate. *)
Lemma wreath_gap_R_le1 (R : realType) : wreath_gap_R R <= 1.
Proof.
rewrite /wreath_gap_R lerBlDr addrC -lerBlDr subrr.
exact: wreath_alpha_R_ge0.
Qed.

(** wreath_gap_R_one_minus — the complement of the gap is alpha.
    Kind: helper. Why: algebraic bridge between alpha and 1 - gap.
    Used by: wreath_spectral_convergence_gap. *)
Lemma wreath_gap_R_one_minus (R : realType) :
  1 - wreath_gap_R R = wreath_alpha_R R.
Proof. by rewrite /wreath_gap_R opprB addrA addrAC subrr add0r. Qed.

(** wreath_spectral_convergence_gap — convergence bound in spectral-gap form.
    Kind: main. Why: the exact shape of SchreierCertificate.sc_convergence. *)
Lemma wreath_spectral_convergence_gap
    (R : realType) (L : nat) (s : 'I_14) :
  var_dist (fdistmap (fun sigma : {perm 'I_14} => sigma s)
                     (rho_from_words L wreath_sym_gens))
           (fdist_uniform (card_ord 14))
  <= Num.sqrt 14%:R * (1 - wreath_gap_R R) ^+ L.
Proof.
rewrite wreath_gap_R_one_minus.
exact: wreath_spectral_convergence_proved.
Qed.

(** wreath_schreier_certificate — the Schreier spectral certificate for the
    symmetric wreath walk.
    Kind: instance. Why: packages gap + convergence into the generic record
    that yields a SecurityAsymptotic with floor 0. *)
Definition wreath_schreier_certificate (R : realType) :
    SchreierCertificate R 4 12 wreath_sym_gens :=
  MkSchreierCertificate
    (wreath_gap_R R)
    (wreath_gap_R_pos R)
    (wreath_gap_R_le1 R)
    (fun L s => wreath_spectral_convergence_gap R L s).

(** wreath_asymptotic — the wreath SecurityAsymptotic, additive floor 0.
    Kind: main. Why: THE deliverable; brings the wreath plug to the S_5
    standard (sa_eps_inf = 0, geometric decay). *)
Definition wreath_asymptotic (R : realType) :
    @SecurityAsymptotic R M_wreath_sym :=
  security_witness_schreier_asymptotic (wreath_schreier_certificate R).

(** wreath_asymptotic_eps_inf_zero — the additive floor is 0.
    Kind: main. Why: the headline parity with s5_eps_inf_zero. *)
Lemma wreath_asymptotic_eps_inf_zero (R : realType) :
  sa_eps_inf (wreath_asymptotic R) = 0.
Proof. by []. Qed.

(** wreath_security_witness_schreier — the Schreier-based SecurityWitness at L.
    Kind: instance. Why: the witness carrying Some wreath_asymptotic, ready to
    rewire the wreath plug. Hlfree is word-eval injectivity at length L; the
    asymptotic itself needs none. *)
Definition wreath_security_witness_schreier (R : realType) (L : nat)
    (Hlfree : @weval_inj M_wreath_sym L) : SecurityWitness R M_wreath_sym :=
  security_witness_schreier (wreath_schreier_certificate R) Hlfree.

(** wreath_security_witness_asymptotic — the plug-ready SecurityWitness at L,
    built directly, carrying Some wreath_asymptotic.
    Kind: instance.
    Why: the witness the MonodromyProfile plug consumes. Unlike
    wreath_security_witness_schreier it needs no word-eval injectivity: the
    sw_bound field is wreath_spectral_convergence_gap itself, mirroring
    s5_security_witness_schreier. This is what makes the wreath plug carry an
    asymptotic, matching the S_5 plug. *)
Definition wreath_security_witness_asymptotic (R : realType) (L : nat) :
    SecurityWitness R M_wreath_sym :=
  @MkSecurityWitness R M_wreath_sym L
    (Num.sqrt 14%:R * (1 - wreath_gap_R R) ^+ L)
    (rho_from_words L wreath_sym_gens)
    (fun s => wreath_spectral_convergence_gap R L s)
    None
    (Some (wreath_asymptotic R)).
