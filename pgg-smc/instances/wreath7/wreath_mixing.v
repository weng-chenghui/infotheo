(*  Section 2. Inverse-closure of the generator multiset.                     *)
(******************************************************************************)

(** wreath_inv_pairing — the index involution pairing each generator with its
    inverse: 0<->1 (cut1<->cut1^-1), 2<->3 (cut2<->cut2^-1), 4 fixed (wswap).
    Kind: helper.
    Why: the bijection on 'I_5 that witnesses inverse-closure of the multiset.
    Used by: wreath_gens_inv_closed, wreath_schreier_symm. *)
Definition wreath_inv_pairing : 'I_5 -> 'I_5 :=
  fun k => tperm (@Ordinal 5 0 isT) (@Ordinal 5 1 isT)
                 (tperm (@Ordinal 5 2 isT) (@Ordinal 5 3 isT) k).

(** wreath_inv_pairing_inv — the index pairing is an involution.
    Kind: helper.
    Why: the pairing is the product of two disjoint transpositions, so it
    equals its own inverse; this makes it a bijection on 'I_5 used to reindex
    the generator count in wreath_schreier_symm.
    Used by: wreath_schreier_symm. *)
Lemma wreath_inv_pairing_inv : involutive wreath_inv_pairing.
Proof.
move=> k; rewrite /wreath_inv_pairing.
by case: k => -[|[|[|[|[|k']]]]] Hk //; apply/val_inj; rewrite !permE /=.
Qed.

(** wreath_gens_inv_closed — every generator's mirror under the pairing is its
    inverse.
    Kind: helper.
    Why: the algebraic content of inverse-closure; drives the symmetry of the
    Schreier transition. Mechanical: compute each of the five indices.
    Used by: wreath_schreier_symm. *)
Lemma wreath_gens_inv_closed (k : 'I_5) :
  tnth wreath_sym_gens (wreath_inv_pairing k)
    = ((tnth wreath_sym_gens k)^-1)%g.
Proof.
case: k => -[|[|[|[|[|k']]]]] Hk //.
all: rewrite /wreath_inv_pairing !permE /=.
all: rewrite !(tnth_nth 1%g) /=.
all: rewrite ?invgK //.
(* index 4: wswap is its own inverse, since wswap^2 = 1 *)
suff Hinv : (wswap * wswap)%g = 1%g.
  by rewrite -(mulg1_eq Hinv) invgK; exact: mulg1_eq Hinv.
apply/permP => x; rewrite perm1 permM.
case: x => -[|[|[|[|[|[|[|[|[|[|[|[|[|[|]]]]]]]]]]]]]] Hx //;
  apply/val_inj; rewrite /wswap !permM !permE; by [].
Qed.

(******************************************************************************)
(*  Section 3. Symmetry of the Schreier transition from inverse-closure.      *)
(******************************************************************************)

(** wreath_schreier_symm — the Schreier transition of the inverse-closed
    multiset is symmetric.
    Kind: main.
    Why: generalises schreier_transition_symm from per-generator involutivity
    to multiset inverse-closure: #{k : g_k i = j} = #{k : g_k j = i} via the
    pairing wreath_inv_pairing. The single structural fact the wreath needs
    that S_5 got for free from involutive transpositions.
    Used by: wreath_spectral_convergence_proved. *)
Lemma wreath_schreier_symm (R : realType) :
  (schreier_transition R wreath_sym_gens)^T
    = schreier_transition R wreath_sym_gens.
Proof.
apply/matrixP => i j; rewrite !mxE.
congr (_%:R / _); rewrite /schreier_gen_count.
(* g_(pairing k) = g_k^-1, hence g_(pairing k) i = j <-> g_k j = i *)
have Heq : forall k,
    (tnth wreath_sym_gens (wreath_inv_pairing k) i == j)
      = (tnth wreath_sym_gens k j == i).
  move=> k; rewrite wreath_gens_inv_closed.
  apply/eqP/eqP => H.
    by rewrite -H permKV.
  by rewrite -H permK.
transitivity
  (#|[set k | tnth wreath_sym_gens (wreath_inv_pairing k) i == j]|).
  by apply: eq_card => k; rewrite !inE Heq.
(* reindex by the involution wreath_inv_pairing, a bijection on 'I_5 *)
rewrite -(card_imset _ (can_inj wreath_inv_pairing_inv)).
apply: eq_card => k; rewrite !inE.
apply/imsetP/idP.
  by move=> [x]; rewrite inE => Hx ->.
move=> Hk; exists (wreath_inv_pairing k);
  rewrite ?inE ?wreath_inv_pairing_inv //.
Qed.

