(* Z_7 wr S_2 wreath spectral convergence: a SecurityAsymptotic for the plug  *)
(*                                                                            *)
(* Brings the wreath plug up to the S_5 standard (see s5_mixing.v): a          *)
(* SecurityAsymptotic with additive floor sa_eps_inf = 0 and geometric decay   *)
(*   var_dist (sigma s) uniform <= sqrt(14) * (1 - gap)^L.                     *)
(*                                                                            *)
(* THE OBSTRUCTION the wreath does not share with S_5.                         *)
(*   The S_5 engine symm_ds_TV_bound derives symmetry of the Schreier          *)
(*   transition from per-generator INVOLUTIVITY (g^2 = 1). The wreath cuts      *)
(*   cut1, cut2 are 7-CYCLES, not involutions, so the 3-generator transition    *)
(*   [cut1; cut2; wswap] is NOT symmetric and that engine does not apply.       *)
(*   (Z_7 has odd order, so the base group cannot be generated by involutions   *)
(*   at all.)                                                                  *)
(*                                                                            *)
(* THE FIX (group-preserving).                                                 *)
(*   Adjoin the inverses: wreath_sym_gens = [cut1; cut1^-1; cut2; cut2^-1;      *)
(*   wswap]. The generating MULTISET is now closed under inverse, so the        *)
(*   Schreier transition is symmetric (wreath_schreier_symm) WITHOUT each       *)
(*   generator being an involution. Adjoining inverses does not change the      *)
(*   generated group (wreath_sym_same_group), so the plug is still Z_7 wr S_2.  *)
(*   The walk is connected on all 14 positions (cut1 mixes pile 1, wswap        *)
(*   crosses to pile 2, cut2 mixes pile 2), hence irreducible: the stationary   *)
(*   law is uniform and sa_eps_inf = 0.                                         *)
(*                                                                            *)
(* The sole imported assumption is wreath_rayleigh_Qsq_R, the Rayleigh bound    *)
(* on Q^2 at alpha^2 over mean-zero vectors, mirroring s5_rayleigh_Qsq_R; it    *)
(* is certified externally by wreath_spectral_certificate.py in this directory. *)
(* Every other step is a structural Rocq proof.                                 *)
