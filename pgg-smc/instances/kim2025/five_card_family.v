(* five_card_family: den Boer and Kim as one epsilon-parameterized profile     *)
(*                                                                            *)
(* The den Boer (1989) five-card trick and the Kim-Cetinkaya (2025) biased     *)
(* analysis live on the SAME group: the cyclic C_5 generated by the 5-cycle    *)
(* fc_sigma. Kim's PGG instance FiveCardKim_M uses all five rotations          *)
(* sigma^0..sigma^4 as generators (so its weight distribution can place a      *)
(* distinct probability on each cut); the original den Boer presentation uses   *)
(* the single generator sigma, and both generate <[fc_sigma]> = C_5. The single *)
(* generator is recovered at eps = 0, the perfectly-uniform regime. This file   *)
(* plugs                                                                        *)
(* the heterogeneous-secret bool/'I_5 threshold scheme fcI_scheme (reused from  *)
(* the den Boer directory, since it depends only on N = 5) onto FiveCardKim_M,  *)
(* and bundles a MonodromyProfile parameterized by Kim's bias eps. At eps = 0   *)
(* the bias disappears and the dealing-phase security bound collapses to 0      *)
(* (the perfectly-uniform den Boer regime).                                     *)
(*                                                                            *)
(* Contents:                                                                  *)
(*   fcI_perm_compatible_kim == reconstruction invariance over the FULL group  *)
(*     pgg_G FiveCardKim_M = <[fc_sigma]> (the five generators still generate   *)
(*     the same C_5, so the rotation argument is identical to den Boer).        *)
(*   FiveCardKim_PI          == the five-sheet starting interface (ord_tuple 5) *)
(*   five_card_plug          == the bool/'I_5 ReconPlug on FiveCardKim_M        *)
(*   five_card_profile       == the eps-parameterized MonodromyProfile          *)
(*   five_card_eps0_perfect  == at eps = 0 the security bound is 0              *)
